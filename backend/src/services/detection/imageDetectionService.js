/**
 * TraceAI Real Image Detection Service
 * Multi-signal inspection: Binary validation, EXIF extraction, C2PA Content Credentials,
 * and dedicated neural visual forensic classifier adapter.
 */

import config from '../../config/environment.js';
import logger from '../../utils/logger.js';
import metadataService from '../media/metadataService.js';
import c2paService from '../provenance/c2paService.js';

const HF_IMAGE_DETECTOR_MODEL = 'umm-maybe/AI-image-detector';

export const imageDetectionService = {
  /**
   * Primary image authenticity analysis pipeline.
   */
  async analyzeImage(buffer, originalFilename, mimeType) {
    logger.info('Analyzing image authenticity', { filename: originalFilename, mimeType, size: buffer.length });

    // 1. Metadata Analysis (EXIF / Software tags)
    const metadata = metadataService.extractImageMetadata(buffer, mimeType);

    // 2. Cryptographic Provenance (C2PA)
    const provenance = c2paService.inspectBuffer(buffer);

    // 3. Neural Classifier Adapter (HuggingFace umm-maybe/AI-image-detector or provider)
    let modelResult = null;
    if (config.aiProviders.hfToken) {
      modelResult = await queryHuggingFaceImageDetector(buffer);
    } else {
      modelResult = {
        isAvailable: false,
        providerName: config.aiProviders.image,
        modelName: HF_IMAGE_DETECTOR_MODEL,
        modelVersion: 'v1.0',
        score: null,
        scoreMeaning: 'HuggingFace image classifier unconfigured (HF_TOKEN not set in environment).'
      };
    }

    // 4. Construct Findings List
    const findings = [
      {
        id: `f-img-prov-${Date.now()}`,
        category: 'provenance',
        title: 'C2PA Provenance Manifest Status',
        description: provenance.manifestFound
          ? `Embedded C2PA Content Credentials detected. Issuer: ${provenance.issuer}. Validation status: ${provenance.validationStatus}.`
          : 'No cryptographic C2PA or Adobe Content Credentials manifest embedded in binary headers.',
        evidenceType: 'cryptographic',
        confidence: provenance.manifestFound ? 'high' : 'neutral',
        metadata: {
          standard: provenance.standard,
          issuer: provenance.issuer,
          status: provenance.validationStatus
        }
      },
      {
        id: `f-img-exif-${Date.now()}`,
        category: 'metadata',
        title: 'Container & EXIF Header Analysis',
        description: metadata.hasExif
          ? `EXIF data present (Camera: ${metadata.cameraMake || 'Unknown'} ${metadata.cameraModel || ''}, Software: ${metadata.software || 'None'}).`
          : 'No standard EXIF camera tags detected. Note: Missing metadata is common across social networks and web optimizers.',
        evidenceType: 'heuristic',
        confidence: metadata.hasExif ? 'notable' : 'neutral',
        metadata: {
          hasExif: metadata.hasExif,
          cameraMake: metadata.cameraMake,
          software: metadata.software
        }
      },
      {
        id: `f-img-neural-${Date.now()}`,
        category: 'neural_vision_classifier',
        title: 'Neural Vision Classifier Status',
        description: modelResult.isAvailable
          ? `Evaluated using dedicated vision model (${modelResult.modelName}).`
          : 'Dedicated AI image classification model is unavailable (HF_TOKEN required).',
        evidenceType: 'statistical',
        confidence: modelResult.score !== null ? 'medium' : 'inconclusive',
        metadata: {
          provider: modelResult.providerName,
          model: modelResult.modelName,
          score: modelResult.score
        }
      }
    ];

    const limitations = [
      'Missing EXIF metadata does NOT prove an image was generated by AI.',
      'Lossy compression algorithms (JPEG 75% or lower) severely obscure sensor pattern noise (PRNU).',
      'Never attribute an image to a particular AI engine without explicit C2PA provenance signatures.',
      'Model results reflect statistical pattern classification and cannot provide legal proof of origin.'
    ];

    const isProvenanceSynthetic = Boolean(provenance.generationInformation?.containsSyntheticAssertion);

    let assessmentLabel = 'Unsigned Standard Image';
    if (isProvenanceSynthetic) {
      assessmentLabel = 'C2PA Synthetic Assertion Signed';
    } else if (modelResult.score !== null) {
      assessmentLabel = modelResult.score > 0.70 ? 'Synthetic Artifacts Indicated' : 'Photographic Characteristics';
    } else if (provenance.manifestFound) {
      assessmentLabel = 'C2PA Cryptographically Signed';
    } else {
      assessmentLabel = 'Inconclusive / Unsigned Asset';
    }

    return {
      provider: modelResult.providerName,
      model: {
        name: modelResult.modelName,
        version: modelResult.modelVersion
      },
      status: 'completed',
      assessment: {
        label: assessmentLabel,
        score: modelResult.score,
        scoreMeaning: modelResult.scoreMeaning,
        limitations
      },
      findings,
      provenance: {
        available: provenance.manifestFound,
        standard: provenance.standard,
        issuer: provenance.issuer,
        validationStatus: provenance.validationStatus,
        sources: provenance.manifestFound ? [provenance.issuer] : []
      },
      metadata: {
        byteLength: metadata.byteLength,
        format: metadata.format,
        hasExif: metadata.hasExif,
        cameraMake: metadata.cameraMake,
        software: metadata.software
      },
      processedAt: new Date().toISOString()
    };
  }
};

async function queryHuggingFaceImageDetector(buffer) {
  try {
    const url = `https://api-inference.huggingface.co/models/${HF_IMAGE_DETECTOR_MODEL}`;
    const response = await fetch(url, {
      method: 'POST',
      headers: {
        'Authorization': `Bearer ${config.aiProviders.hfToken}`
      },
      body: buffer
    });

    if (!response.ok) {
      logger.warn('HuggingFace image detection returned non-200 status', { status: response.status });
      return {
        isAvailable: false,
        providerName: 'huggingface',
        modelName: HF_IMAGE_DETECTOR_MODEL,
        modelVersion: 'v1.0',
        score: null,
        scoreMeaning: `HuggingFace API returned HTTP ${response.status}.`
      };
    }

    const json = await response.json();
    let artificialScore = null;
    if (Array.isArray(json)) {
      const artEntry = json.find(e => e.label?.toLowerCase().includes('artificial') || e.label === 'LABEL_1');
      if (artEntry) artificialScore = parseFloat(artEntry.score.toFixed(3));
    }

    return {
      isAvailable: true,
      providerName: 'huggingface',
      modelName: HF_IMAGE_DETECTOR_MODEL,
      modelVersion: 'v1.0',
      score: artificialScore,
      scoreMeaning: 'HuggingFace ViT artificial image classifier probability.'
    };
  } catch (err) {
    logger.error('HuggingFace image request error', { error: err.message });
    return {
      isAvailable: false,
      providerName: 'huggingface',
      modelName: HF_IMAGE_DETECTOR_MODEL,
      modelVersion: 'v1.0',
      score: null,
      scoreMeaning: `HuggingFace request failed: ${err.message}`
    };
  }
}

export default imageDetectionService;
